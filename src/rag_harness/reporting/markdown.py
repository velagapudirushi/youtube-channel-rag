"""GitHub-Flavored Markdown report generator for CI/CD PR comments and repo documentation."""

from __future__ import annotations

from typing import Sequence

from rag_harness.schemas import HarnessReport


def generate_markdown_report(report: HarnessReport) -> str:
    """Generate a detailed GitHub-Flavored Markdown report for a single RAG pipeline run."""
    lines: list[str] = [
        f"# RAG Evaluation Report: `{report.pipeline_name}`",
        "",
        f"- **Dataset:** `{report.dataset_name}` ({report.total_queries} queries, cutoff `K={report.k}`)",
        f"- **Overall Pass Rate:** **{report.pass_rate:.1%}** ({report.passed_queries}/{report.total_queries})",
        f"- **Cross-Checked Faithfulness:** **{report.mean_cross_checked_faithfulness:.1%}** "
        f"(LLM-Judge: `{report.mean_llm_faithfulness:.1%}` vs. NLI-Entailment: `{report.mean_nli_faithfulness:.1%}`)",
        f"- **Judge-NLI Disagreements Flagged:** `{report.total_judge_disagreements}` / `{report.total_claims_evaluated}` atomic claims (`{report.disagreement_rate:.1%}`)",
        f"- **Mean Latency:** `{report.mean_latency_ms:.1f} ms`",
        "",
        "## 1. Retrieval & Faithfulness Summary",
        "",
        "| Category | Metric | Score | Notes |",
        "| :--- | :--- | :---: | :--- |",
        f"| **Retrieval** | `Recall@{report.k}` | **{report.mean_recall_at_k:.1%}** | Fraction of golden chunks retrieved in top-{report.k} |",
        f"| **Retrieval** | `Precision@{report.k}` | `{report.mean_precision_at_k:.1%}` | Signal-to-noise ratio in top-{report.k} window |",
        f"| **Retrieval** | `MRR` | **{report.mean_mrr:.3f}** | Reciprocal rank of first golden chunk |",
        f"| **Retrieval** | `NDCG@{report.k}` | **{report.mean_ndcg_at_k:.3f}** | Rank-aware retrieval quality |",
        f"| **Retrieval** | `Context Fact Coverage` | `{report.mean_context_coverage:.1%}` | Reference key facts present in retrieved text |",
        f"| **Faithfulness** | `Method A: LLM-as-a-Judge` | `{report.mean_llm_faithfulness:.1%}` | Holistic passage-level judge |",
        f"| **Faithfulness** | `Method B: NLI Entailment` | `{report.mean_nli_faithfulness:.1%}` | Sentence-aligned premise-hypothesis cross-encoder |",
        f"| **Faithfulness** | **`Cross-Checked Score`** | **{report.mean_cross_checked_faithfulness:.1%}** | Calibrated ensemble penalizing NLI contradictions |",
        "",
    ]

    if not report.representative_failures:
        lines.append("## 2. Representative Failures\n\nAll queries passed retrieval and faithfulness checks.")
        return "\n".join(lines)

    lines.extend(["## 2. Representative Failure Taxonomy", ""])
    for bucket in report.representative_failures:
        lines.extend(
            [
                f"### `{bucket.category.value}` — {bucket.title} ({bucket.count} queries / {bucket.percentage:.1f}%)",
                "",
                f"> **Why this happens:** {bucket.description}",
                f">",
                f"> **Recommended Fix:** {bucket.remediation}",
                "",
            ]
        )
        for idx, ex in enumerate(bucket.examples, start=1):
            lines.extend(
                [
                    f"#### Representative Failure #{idx}: `{ex.query_id}` — *{ex.question}*",
                    f"- **Retrieved Chunks:** `{ex.retrieved_chunk_ids}` (Golden: `{ex.golden_chunk_ids}`, First Hit Rank: `{ex.first_relevant_rank or 'MISSED'}`)",
                    f"- **Generated Answer:** {ex.generated_answer}",
                    f"- **Ground Truth:** {ex.ground_truth_answer}",
                    f"- **Faithfulness Breakdown:** LLM Judge `{ex.llm_judge_score:.2f}` | NLI Entailment `{ex.nli_entailment_score:.2f}` | **Cross-Checked `{ex.cross_checked_score:.2f}`**",
                    f"- **Root Cause Diagnosis:** {ex.failure_explanation}",
                ]
            )
            if ex.flagged_claims:
                lines.append("- **Flagged Atomic Claims:**")
                for fc in ex.flagged_claims:
                    badge = f" ⚠️ **[{fc.disagreement_type}]**" if not fc.agreement else ""
                    lines.append(
                        f"  - `\"{fc.claim_text}\"` → LLM: `{fc.llm_verdict.value}`, "
                        f"NLI: `{fc.nli_label.value}` (`E={fc.nli_probabilities.entailment:.2f}`, "
                        f"`C={fc.nli_probabilities.contradiction:.2f}`){badge}"
                    )
            lines.append("")

    return "\n".join(lines)


def generate_benchmark_comparison_markdown(reports: Sequence[HarnessReport]) -> str:
    """Generate a head-to-head Markdown benchmark report across multiple RAG repos."""
    lines: list[str] = [
        "# Multi-Repo RAG Evaluation Benchmark Report",
        "",
        "Generated by **`rag-eval-harness`** — comparing retrieval metrics, single-method LLM-Judge vs. NLI-Entailment cross-checked faithfulness, and root-cause failure distributions across 3 RAG architectures.",
        "",
        "## 1. Head-to-Head Metrics Comparison",
        "",
        "| RAG Repo / Architecture | Pass Rate | Recall@K | MRR | NDCG@K | LLM-Judge Only | NLI Entailment | **Cross-Checked Faithfulness** | Judge-NLI Disagreements | Mean Latency |",
        "| :--- | :---: | :---: | :---: | :---: | :---: | :---: | :---: | :---: | :---: |",
    ]
    for r in reports:
        lines.append(
            f"| **`{r.pipeline_name}`** | **{r.pass_rate:.1%}** ({r.passed_queries}/{r.total_queries}) | "
            f"`{r.mean_recall_at_k:.1%}` | `{r.mean_mrr:.3f}` | `{r.mean_ndcg_at_k:.3f}` | "
            f"`{r.mean_llm_faithfulness:.1%}` | `{r.mean_nli_faithfulness:.1%}` | "
            f"**{r.mean_cross_checked_faithfulness:.1%}** | "
            f"`{r.total_judge_disagreements}/{r.total_claims_evaluated}` ({r.disagreement_rate:.1%}) | "
            f"`{r.mean_latency_ms:.1f} ms` |"
        )

    lines.extend(["", "## 2. Failure Mode Distribution by Architecture", ""])
    all_cats = [
        "JUDGE_NLI_DISAGREEMENT",
        "INTRINSIC_CONTRADICTION",
        "EXTRINSIC_HALLUCINATION",
        "RETRIEVAL_MISS",
        "LOST_IN_THE_MIDDLE",
        "INCOMPLETE_SYNTHESIS",
    ]
    header = "| Failure Bucket | " + " | ".join(f"`{r.pipeline_name}`" for r in reports) + " |"
    sep = "| :--- | " + " | ".join(":---:" for _ in reports) + " |"
    lines.extend([header, sep])
    for cat in all_cats:
        row_cells = [str(r.failure_distribution.get(cat, 0)) for r in reports]
        lines.append(f"| `{cat}` | " + " | ".join(row_cells) + " |")

    lines.extend(["", "---", ""])
    for r in reports:
        lines.append(generate_markdown_report(r))
        lines.extend(["", "---", ""])

    return "\n".join(lines)
